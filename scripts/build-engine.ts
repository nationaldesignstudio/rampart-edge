#!/usr/bin/env bun
/**
 * Build the Rust engine with the pinned toolchain and generate `src/engine-wasm.ts`.
 *
 *   bun scripts/build-engine.ts          build → runtime/rampart-engine.wasm + src/engine-wasm.ts
 *   bun scripts/build-engine.ts --check  build to a temp dir and fail unless byte-identical to the committed
 *                                        wasm and generated module (also enforces the raw size budget)
 *   bun scripts/build-engine.ts --gen    only regenerate src/engine-wasm.ts from the committed wasm
 */
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const crate = join(root, "engine");
const wasmOut = join(root, "runtime", "rampart-engine.wasm");
const tsOut = join(root, "src", "engine-wasm.ts");
export const SIZE_BUDGET_BYTES = 48 * 1024;

const args = new Set(process.argv.slice(2));
const check = args.has("--check");
const genOnly = args.has("--gen");

function sha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

function renderModule(wasm: Uint8Array): string {
  const b64 = Buffer.from(wasm).toString("base64");
  const lines: string[] = [];
  for (let i = 0; i < b64.length; i += 120) lines.push(`  "${b64.slice(i, i + 120)}"`);
  return [
    "// Generated by scripts/build-engine.ts from runtime/rampart-engine.wasm. Do not edit.",
    `// wasm sha256: ${sha256(wasm)}`,
    `// wasm bytes: ${wasm.byteLength}`,
    "",
    `export const ENGINE_WASM_SHA256 = "${sha256(wasm)}";`,
    `export const ENGINE_WASM_BYTES = ${wasm.byteLength};`,
    "export const ENGINE_WASM_BASE64: string =",
    lines.join(" +\n") + ";",
    "",
  ].join("\n");
}

async function cargoBuild(targetDir: string): Promise<Uint8Array> {
  const proc = Bun.spawn(["cargo", "build", "--release", "--target", "wasm32-unknown-unknown", "--target-dir", targetDir], {
    cwd: crate,
    stdout: "inherit",
    stderr: "inherit",
    env: { ...process.env, CARGO_TERM_COLOR: "never" },
  });
  if ((await proc.exited) !== 0) throw new Error("cargo build failed");
  return new Uint8Array(readFileSync(join(targetDir, "wasm32-unknown-unknown", "release", "rampart_engine.wasm")));
}

function assertBudget(wasm: Uint8Array): void {
  if (wasm.byteLength > SIZE_BUDGET_BYTES) {
    throw new Error(`engine wasm is ${wasm.byteLength} bytes, over the ${SIZE_BUDGET_BYTES}-byte budget`);
  }
  const imports = WebAssembly.Module.imports(new WebAssembly.Module(wasm.slice().buffer as ArrayBuffer));
  if (imports.length !== 0) throw new Error(`engine wasm must import nothing, got ${JSON.stringify(imports)}`);
}

if (genOnly) {
  const wasm = new Uint8Array(readFileSync(wasmOut));
  assertBudget(wasm);
  writeFileSync(tsOut, renderModule(wasm));
  console.log(`wrote ${tsOut} (${wasm.byteLength} bytes, sha256 ${sha256(wasm)})`);
} else if (check) {
  const tmp = mkdtempSync(join(tmpdir(), "rampart-engine-"));
  try {
    const built = await cargoBuild(tmp);
    assertBudget(built);
    if (!existsSync(wasmOut)) throw new Error(`${wasmOut} is missing`);
    const committed = new Uint8Array(readFileSync(wasmOut));
    if (sha256(built) !== sha256(committed)) {
      throw new Error(`rebuilt wasm (${built.byteLength} B, ${sha256(built)}) differs from committed (${committed.byteLength} B, ${sha256(committed)})`);
    }
    const ts = readFileSync(tsOut, "utf8");
    if (ts !== renderModule(committed)) throw new Error(`${tsOut} is stale; run bun scripts/build-engine.ts`);
    console.log(`ok: ${wasmOut} reproducible, ${built.byteLength} bytes (budget ${SIZE_BUDGET_BYTES}), sha256 ${sha256(built)}`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const built = await cargoBuild(join(crate, "target"));
  assertBudget(built);
  writeFileSync(wasmOut, built);
  writeFileSync(tsOut, renderModule(built));
  console.log(`wrote ${wasmOut} (${built.byteLength} bytes, sha256 ${sha256(built)}) and ${tsOut}`);
}
